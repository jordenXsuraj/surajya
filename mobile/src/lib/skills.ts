/** Web's (commented-out) roadmap placeholders, by branch. */
export function roadmapPlaceholder(branch: string): string {
  if (branch === 'Civil') {
    return 'e.g. Learning AutoCAD, working on site survey project…\n\nTarget: internship at civil firm';
  }
  if (branch === 'Mechanical') {
    return 'e.g. Learning SolidWorks, building robot arm…\n\nTarget: core mechanical placement';
  }
  return 'e.g. Learning React, solving DSA daily…\n\nTarget: placements in 6 months';
}
